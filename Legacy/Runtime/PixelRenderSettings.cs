using System;
using UnityEngine;

namespace EliotByte.PixelRender.Legacy
{
	/// <summary>
	/// Настройки пиксельного вида объектов. Общие — на PixelRenderManager (камера), объект может включить свои.
	/// </summary>
	public enum BakeTransition
	{
		[Tooltip("Сетка старого ракурса плавно перетекает в новую.")]
		Morph,
		[Tooltip("Клетки новой сетки проявляются поверх старой по случайному порогу.")]
		Dissolve
	}

	[Serializable]
	public class PixelRenderSettings
	{
		[Header("Размер пикселя")]
		[Tooltip("Размер пикселя объекта в пикселях экрана при высоте кадра 720 (масштабируется с высотой: " +
		         "7 → ~1/100 высоты кадра, на 1080p ≈ 10) — одинаковый у всех объектов на любом расстоянии.")]
		[Min(1f)] public float CellPixels = 7f;
		[Tooltip("То же для объектов с экранной сеткой (пол и большие поверхности).")]
		[Min(1f)] public float ScreenCellPixels = 7f;
		[Tooltip("Целое число пикселей экрана на пиксель объекта — пиксели ровные, без «то 2, то 3».")]
		public bool IntegerCells;
		[Tooltip("Размер пикселя масштабируется с высотой кадра (Cell Pixels и Screen Cell Pixels заданы для 720p). " +
		         "Выключено — ровно столько пикселей экрана при любом разрешении (6 → пиксель объекта = 6×6 пикселей экрана).")]
		public bool ScaleWithScreen = true;

		[Header("Размер от текстуры (вместо Cell Pixels)")]
		[Tooltip("Пиксель = тексель (клетка шахматки) / Pixels Per Texel: уменьшается с расстоянием, как в перспективе. " +
		         "Размер клетки меняется каждый кадр — пиксели больше ползают при движении.")]
		public bool AutoFromTexels;
		[Range(1, 8)] public int PixelsPerTexel = 3;
		[Tooltip("Минимальный размер пикселя на экране (для Auto From Texels).")]
		[Min(1f)] public float MinScreenPixel = 2f;

		[Header("Запекание на поверхность")]
		[Tooltip("Сетка объекта запоминается («запекается») и обновляется только при заметной смене ракурса. " +
		         "Между обновлениями клетки приклеены к объекту и не меняются; край объекта — ступеньками по сетке " +
		         "каждый кадр. Не действует на объекты с экранной сеткой (пол) и с Auto From Texels.")]
		public bool SurfaceBake = true;
		[Tooltip("Перезапекать, когда направление взгляда на объект (или поворот камеры вокруг взгляда) ушло на столько градусов.")]
		[Range(0.5f, 45f)] public float BakeAngle = 6f;
		[Tooltip("Перезапекать, когда размер клетки на объекте изменился больше чем на эту долю (приближение/отдаление).")]
		[Range(0.02f, 1f)] public float BakeScale = 0.15f;
		[Tooltip("Картинка момента запекания (уже пиксельная: клетка — один цвет, вместе с краем) натягивается на объект " +
		         "до следующего запекания — ни узор, ни силуэт не дрожат. Клетки, закрытые другими объектами в момент запекания, " +
		         "рисуются по текущей сетке. Выключено — узор пересчитывается по поверхности объекта, край — текущей сеткой.")]
		public bool BakeSilhouette = true;
		[Tooltip("Живой силуэт: край объекта каждый кадр сверяется с текущей геометрией (клетки спрайта занимаются и " +
		         "освобождаются по доле покрытия, с гистерезисом), а узор внутри остаётся запечённым. Выключено — край " +
		         "тоже запечён и до следующего запекания может отставать (зубцы).")]
		public bool LiveSilhouette = true;
		[Tooltip("Гистерезис края: клетка занимается при покрытии > 0.5 + это значение и освобождается при < 0.5 − это значение.")]
		[Range(0f, 0.45f)] public float EdgeHysteresis = 0.2f;
		[Tooltip("Перезапекать, когда ожидаемый сдвиг края объекта (из-за масштаба и поворота) превысил столько клеток. " +
		         "Крупные и близкие объекты обновляются чаще, мелкие и далёкие — реже. 0 — выключено (только Bake Angle / Bake Scale).")]
		[Range(0f, 4f)] public float BakeMaxError = 1f;
		[Tooltip("Как переходить от старого ракурса к новому: Morph — сетка плавно перетекает, Dissolve — растворение клетками.")]
		public BakeTransition Transition = BakeTransition.Morph;
		[Tooltip("Время перехода от старого ракурса к новому, секунды (0 — мгновенно).")]
		[Range(0f, 2f)] public float BakeDissolve;

		[Header("Контур")]
		public bool Outline;
		public Color OutlineColor = new(0.06f, 0.06f, 0.08f, 1f);

		/// <summary>Множитель Cell Pixels / Screen Cell Pixels для кадра такой высоты.</summary>
		public float ScreenScale(float height) => ScaleWithScreen ? height / 720f : 1f;
	}
}
